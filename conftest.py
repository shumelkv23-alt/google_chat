# не перезаписывает уже заданные переменные, так что локально реальные значения из
# окружения сохраняются. Юнит-тесты не ходят в БД/сеть, поэтому фейков достаточно.
os.environ.setdefault("DATABASE_URL", "postgresql+asyncpg://test:test@localhost/test")
os.environ.setdefault("OPENAI_API_KEY", "test-key")


@pytest.fixture
def anyio_backend() -> str:
    """Гонять async-тесты (@pytest.mark.anyio) только на asyncio-бэкенде.

    Плагин anyio без этой фикстуры не знает, на каком движке запускать корутины
    (и пытался бы ещё trio). Возвращаем строку, а не список, — только asyncio.
    """
    return "asyncio"
